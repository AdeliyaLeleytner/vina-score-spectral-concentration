#!/usr/bin/env python3
"""Equivalence-margin sensitivity curve for the residual-minus-absolute ranking contrast.

Reviewer point (Major Revision, cross-lab review).  The Results text asserted a
*prespecified* symmetric equivalence margin of +/-0.03 while the Methods section of the
same manuscript states that equivalence readings are post hoc and that the 0.02/0.05
margins "are not interpreted as prospectively specified tests".  That is a flat
contradiction.  The margin is being relabelled post hoc, and a single threshold is
replaced by the whole sensitivity curve.

This script is a read-and-tabulate job.  It re-runs no bootstrap.  It reads the frozen
5,000-replicate chemical-cluster intervals that the dense and broad benchmarks already
wrote, forms the package's conservative union of the two chemical-cluster schemes
(Murcko/Bemis-Murcko scaffold and Butina), and for every symmetric margin on a
0.010--0.060 grid in steps of 0.005 records whether two one-sided tests at alpha = 0.05
pass.  A symmetric-margin TOST at alpha rejects both one-sided nulls exactly when the
(1 - 2*alpha) interval lies strictly inside the margin, so the 90% interval is the object
that decides the test; the 95% union is carried alongside as the two-sided estimate that
the manuscript reports as its primary result.

Estimand throughout: mean per-ligand pairwise concordance of the scaled two-way-residual
Vina rule minus plain absolute Vina, on within-ligand target pairs.

Nothing here is a confirmatory test.  No margin was preregistered; every margin on the
grid was chosen after the corresponding benchmark had been computed.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

try:  # Support direct CLI execution and package-style imports.
    from . import make_reported_results as reported
except ImportError:  # pragma: no cover - direct CLI execution.
    import make_reported_results as reported  # type: ignore


PACKAGE = Path(__file__).resolve().parents[1]
RESULTS = PACKAGE / "results"
DEFAULT_OUTPUT = RESULTS / "equivalence_margin_sensitivity" / "summary.json"

CONTRAST = "two_way_residual_minus_absolute_vina"

# Grid endpoints in thousandths so the margin values are generated by integer arithmetic
# and are byte-identical across reruns and platforms.
MARGIN_GRID_MILLI = tuple(range(10, 61, 5))

# The margin the Results section used to call prespecified.  It is read from the reporting
# layer rather than restated here, and is retained only so the curve can say explicitly
# whether that one reading survives once it is relabelled post hoc.
RELABELLED_MANUSCRIPT_MARGIN = reported.DENSE_EQUIVALENCE_MARGIN

ALPHA = 0.05
DECISION_RULE = (
    "two one-sided tests at alpha = 0.05: equivalence is declared when the conservative "
    "union of the two chemical-cluster 90% bootstrap intervals lies strictly inside "
    "(-margin, +margin), i.e. when max(|lower|, |upper|) < margin"
)


def margin_values() -> list[float]:
    return [milli / 1000.0 for milli in MARGIN_GRID_MILLI]


def margin_label(milli: int) -> str:
    return f"{milli / 1000.0:.3f}"


def half_width(interval: list[float]) -> float:
    return max(abs(interval[0]), abs(interval[1]))


def margin_curve(interval_90: list[float]) -> tuple[dict[str, bool], float | None]:
    """Decisions on the fixed grid plus the smallest grid margin that passes."""
    reach = half_width(interval_90)
    decisions: dict[str, bool] = {}
    smallest_passing: float | None = None
    for milli in MARGIN_GRID_MILLI:
        margin = milli / 1000.0
        passes = reach < margin
        decisions[margin_label(milli)] = passes
        if passes and smallest_passing is None:
            smallest_passing = margin
    return decisions, smallest_passing


def contrast_block(
    *,
    plugin_mean_difference: float,
    scheme_intervals_90: dict[str, list[float]],
    scheme_intervals_95: dict[str, list[float]],
    scheme_order: tuple[str, ...],
) -> dict[str, Any]:
    union_90 = reported.interval_union(
        {name: {"interval_90": value} for name, value in scheme_intervals_90.items()},
        scheme_order,
        level="interval_90",
    )
    union_95 = reported.interval_union(
        {name: {"interval_95": value} for name, value in scheme_intervals_95.items()},
        scheme_order,
        level="interval_95",
    )
    decisions, smallest_passing = margin_curve(union_90)
    reach = half_width(union_90)
    return {
        "plugin_mean_difference": plugin_mean_difference,
        "cluster_bootstrap_intervals_90": {
            name: scheme_intervals_90[name] for name in scheme_order
        },
        "conservative_union_interval_90": union_90,
        "conservative_union_interval_95": union_95,
        "interval_90_half_width": reach,
        "smallest_supported_symmetric_margin_90_exact": reach,
        "smallest_supported_symmetric_margin_90_rounded_up_3dp": (
            reported.smallest_equivalence_margin(union_90)
        ),
        "smallest_grid_margin_passing": smallest_passing,
        "margin_decisions_90": decisions,
        "relabelled_manuscript_margin_passes": (
            reach < RELABELLED_MANUSCRIPT_MARGIN
        ),
        "excludes_zero_90": union_90[0] > 0.0 or union_90[1] < 0.0,
    }


def davis_block(davis: dict[str, Any]) -> dict[str, Any]:
    stratum = davis["primary"]["paired_comparisons"][CONTRAST]["0.0"]["all_informative"]
    representation = davis["primary"]["representations"]["absolute_vina"]["0.0"][
        "all_informative"
    ]
    schemes = ("murcko_cluster_bootstrap", "butina_cluster_bootstrap")
    uncertainty = stratum["uncertainty"]
    block = contrast_block(
        plugin_mean_difference=stratum["plugin_mean_difference"],
        scheme_intervals_90={
            name: uncertainty[name]["interval_90"] for name in schemes
        },
        scheme_intervals_95={
            name: uncertainty[name]["interval_95"] for name in schemes
        },
        scheme_order=schemes,
    )
    block["benchmark"] = "DAVIS"
    block["source"] = "results/dense_davis_benchmark.json"
    block["estimand_path"] = (
        f"primary.paired_comparisons.{CONTRAST}.0.0.all_informative"
    )
    block["stratum"] = (
        "all informative within-ligand target pairs: exact pKd ties and floor--floor "
        "pairs at the pKd = 5 reporting floor removed"
    )
    block["support"] = {
        "matched_ligands": davis["source_support"]["primary_full_key_ligands"],
        "evaluated_ligands": representation["evaluated_ligands"],
        "targets": davis["source_support"]["shared_targets"],
        "evaluated_within_ligand_target_pairs": representation["evaluated_pairs"],
        "observed_experimental_cells": davis["source_support"][
            "primary_experimental_cells"
        ],
        "murcko_scaffold_clusters": uncertainty["murcko_cluster_bootstrap"][
            "n_clusters"
        ],
        "butina_clusters": uncertainty["butina_cluster_bootstrap"]["n_clusters"],
        "bootstrap_replicates_per_scheme": uncertainty["murcko_cluster_bootstrap"]["n"],
    }
    block["seed"] = davis["analysis_parameters"]["seed"]
    return block


