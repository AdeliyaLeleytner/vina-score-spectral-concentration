#!/usr/bin/env python3
"""Generate high-risk manuscript numbers and the main spectral comparison table."""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"


def interval_union(record: dict, names: tuple[str, ...], level: str = "interval_95") -> list[float]:
    intervals = [record[name][level] for name in names]
    return [min(value[0] for value in intervals), max(value[1] for value in intervals)]


def macro(name: str, value: str) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def build(evidence: dict) -> tuple[str, str, dict]:
    expanded = evidence["expanded_target_preference_benchmark"]
    broad = expanded["primary_all_exact"]
    kikd = expanded["assay_sensitivities"]["human_binding_Ki_Kd"]
    same_endpoint = expanded["assay_sensitivities"][
        "same_endpoint_pairs_on_fixed_primary_support"
    ]
    duplicate_collapsed = same_endpoint["duplicate_collapsed_unique_target_pairs"]
    noise = evidence["experimental_sensitivity"][
        "reproducibility_calibrated_noise_injection_74x6"
    ]
    residual_absolute = broad["paired_comparisons"][
        "two_way_residual_minus_absolute_vina"
    ]
    residual_column = broad["paired_comparisons"][
        "two_way_residual_minus_column_standardized"
    ]
    residual_absolute_union = interval_union(
        residual_absolute,
        ("scaffold_cluster_bootstrap", "butina_cluster_bootstrap"),
    )
    residual_column_union = interval_union(
        residual_column,
        ("scaffold_cluster_bootstrap", "butina_cluster_bootstrap"),
    )
    cohort_interval = broad["representations"]["cohort_experimental_target_prior"][
        "scaffold_cluster_bootstrap"
    ]["interval_95"]
    macros = {
        "NoisePRMedian": f"{noise['docking_rank_with_noise_median']:.3f}",
        "NoisePRLow": f"{noise['docking_rank_with_noise_95_interval'][0]:.2f}",
        "NoisePRHigh": f"{noise['docking_rank_with_noise_95_interval'][1]:.2f}",
        "ResidualAbsoluteLow": f"{residual_absolute_union[0]:.3f}",
        "ResidualAbsoluteHigh": f"{residual_absolute_union[1]:.3f}",
        "ResidualColumnLow": f"{residual_column_union[0]:.3f}",
        "ResidualColumnHigh": f"{residual_column_union[1]:.3f}",
        "CohortPriorLow": f"{cohort_interval[0]:.3f}",
        "CohortPriorHigh": f"{cohort_interval[1]:.3f}",
        "BroadAbsoluteAccuracy": f"{broad['representations']['absolute_vina']['mean_per_ligand_pairwise_accuracy']:.3f}",
        "BroadColumnAccuracy": f"{broad['representations']['column_standardized']['mean_per_ligand_pairwise_accuracy']:.3f}",
        "BroadResidualAccuracy": f"{broad['representations']['two_way_residual']['mean_per_ligand_pairwise_accuracy']:.3f}",
        "KiKdAbsoluteAccuracy": f"{kikd['representations']['absolute_vina']['mean_per_ligand_pairwise_accuracy']:.3f}",
        "KiKdColumnAccuracy": f"{kikd['representations']['column_standardized']['mean_per_ligand_pairwise_accuracy']:.3f}",
        "KiKdResidualAccuracy": f"{kikd['representations']['two_way_residual']['mean_per_ligand_pairwise_accuracy']:.3f}",
        "DuplicateCollapsedAbsoluteAccuracy": f"{duplicate_collapsed['representations']['absolute_vina']['mean_per_ligand_pairwise_accuracy']:.3f}",
        "DuplicateCollapsedColumnAccuracy": f"{duplicate_collapsed['representations']['column_standardized']['mean_per_ligand_pairwise_accuracy']:.3f}",
        "DuplicateCollapsedResidualAccuracy": f"{duplicate_collapsed['representations']['two_way_residual']['mean_per_ligand_pairwise_accuracy']:.3f}",
    }
    macro_text = "% Generated by analysis/make_reported_results.py; do not edit.\n"
    macro_text += "\n".join(macro(name, value) for name, value in macros.items()) + "\n"

    table_lines = [
        "% Generated by analysis/make_reported_results.py; do not edit.",
        r"\begin{table}[t]",
        r"\centering\small",
        r"\setlength{\tabcolsep}{4pt}",
        r"\caption{\textbf{Complementary summaries of target dependence.} PR and mean squared off-diagonal correlation are algebraically equivalent for a correlation matrix; mean absolute correlation retains a more familiar correlation scale, while PC1 reports concentration in only the leading mode.}",
        r"\label{tab:spectralmetrics}",
        r"\begin{tabular}{llrrrr}",
        r"\toprule Matrix & surface & PR & mean $r^2$ & mean $|r|$ & PC1 \\",
        r"\midrule",
    ]
    for key, label in [("docking44", "Docking-44"), ("dockstring58", "DOCKSTRING-58")]:
        for surface, surface_label in [("raw", "column-standardized"), ("interaction", "residual")]:
            record = evidence["centering_ladder"][key][surface]
            table_lines.append(
                f"{label} & {surface_label} & {record['participation_ratio']:.2f} & "
                f"{record['mean_squared_offdiagonal_correlation']:.3f} & "
                f"{record['mean_absolute_offdiagonal_correlation']:.3f} & "
                f"{record['pc1_fraction']:.3f} \\\\"
            )
    table_lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}", ""])
    registry = {
        "source": "results/evidence_summary.json",
        "macros": macros,
        "rounding": "round-half-even through Python fixed-point formatting",
    }
    return macro_text, "\n".join(table_lines), registry


def main() -> None:
    evidence = json.loads((RESULTS / "evidence_summary.json").read_text())
    macro_text, table_text, registry = build(evidence)
    (RESULTS / "evidence_macros.tex").write_text(macro_text)
    (RESULTS / "main_spectral_metrics_table.tex").write_text(table_text)
    (RESULTS / "reported_values.json").write_text(json.dumps(registry, indent=2) + "\n")
    print("Wrote evidence macros, main spectral table and reported-value registry")


if __name__ == "__main__":
    main()
