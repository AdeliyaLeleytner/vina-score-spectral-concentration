#!/usr/bin/env python3
"""Boundary audit for residual docking geometry and ChEMBL target retrieval.

The audit answers a deliberately narrow operational question: does the larger
spectral dimension exposed by two-way centering improve recovery of known active
targets?  It reconstructs the strict ChEMBL active-pair benchmark entirely from
frozen package inputs and compares three score representations:

* ``absolute``: clipped and column-mean-imputed Vina scores;
* ``column_z``: target-wise z scores across the full Docking-44 support; and
* ``two_way_residual``: the two-way ANOVA residual in raw score units.

Subtracting a row constant cannot change within-ligand target order.  Therefore
``column_z`` and ``two_way_residual`` need NOT have identical rankings; this is an
explicit tested identity, not an empirical approximation.

Inference has two levels.  Paired uncertainty is estimated by resampling whole
compounds and frozen Butina clusters.  Null performance is estimated both by a
legacy target-frequency-multiset permutation and by a stricter bipartite switch
chain that preserves every compound's active-target count, every target's
frequency, and binary compound-target incidence.

No row-level compound, structure, target, or activity identifiers are written to
the output directory.  Only aggregate CSV/JSON records and an autogenerated
README are emitted.
"""

